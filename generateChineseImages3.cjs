const fs = require('fs');
const path = require('path');

// Helper to read file as text
function readFile(file) {
  return fs.readFileSync(file, 'utf8');
}

// Extract city map (ID -> Chinese name) from cities.ts and extra
function extractCityMap() {
  const map = {};
  // From cities.ts: get city objects (those with countryId)
  const citiesText = readFile('./src/data/cities.ts');
  const blocks = citiesText.split('},');
  for (const block of blocks) {
    if (block.includes('countryId:')) {
      const idMatch = block.match(/id:\s*'([^']+)'/);
      const nameMatch = block.match(/name:\s*'([^']+)'/);
      if (idMatch && nameMatch) {
        map[idMatch[1]] = nameMatch[1];
      }
    }
  }
  // Extra cities
  const extraCityMap = {
    cs: '长沙',
    heb: '哈尔滨',
    xm: '厦门',
    sz: '苏州',
    dh: '敦煌',
    zjjs: '张家界',
    ls: '拉萨',
    sy: '三亚',
    py: '平遥',
    wy: '婺源',
    fh: '凤凰'
  };
  Object.assign(map, extraCityMap);
  return map;
}

const cityMap = extractCityMap();
console.log('City map (ID -> Chinese name):', cityMap);

// Build prefix to cityId mapping from existing ID-named directories
const baseDir = path.resolve('./public/images/poi');
const prefixToCityId = {};
for (const cityId of Object.keys(cityMap)) {
  const dirPath = path.join(baseDir, cityId);
  if (fs.existsSync(dirPath)) {
    const files = fs.readdirSync(dirPath);
    for (const file of files) {
      if (file.endsWith('.jpg')) {
        const poiId = path.parse(file).name; // filename without extension
        const prefix = poiId.split('-')[0];
        // Only set if not already set (should be consistent)
        if (!(prefix in prefixToCityId)) {
          prefixToCityId[prefix] = cityId;
        }
      }
    }
  }
}
console.log('Prefix to cityId mapping:', prefixToCityId);

// Extract poi id:name map from both files
function extractPoiMap(text) {
  const map = {};
  const lines = text.split('\n');
  for (const line of lines) {
    const idMatch = line.match(/id:\s*'([^']+)'/);
    const nameMatch = line.match(/name:\s*'([^']+)'/);
    if (idMatch && nameMatch) {
      map[idMatch[1]] = nameMatch[1];
    }
    const idMatch2 = line.match(/id:\s*"([^"]+)"/);
    const nameMatch2 = line.match(/name:\s*"([^"]+)"/);
    if (idMatch2 && nameMatch2) {
      map[idMatch2[1]] = nameMatch2[1];
    }
  }
  return map;
}

