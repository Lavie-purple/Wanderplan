export async function geocodeCityName(
  name: string,
  tiandituKey: string,
): Promise<[number, number] | null> {
  if (cache.has(name)) return cache.get(name) ?? null

  // 0. 硬编码常见中国城市（最稳定，覆盖 4 直辖市 + 27 省会 + ~270 地级市）
  if (KNOWN_CITIES[name]) {
    const p = KNOWN_CITIES[name]
    cache.set(name, p)
    return p
  }

  // 1. 天地图地理编码（使用用户已配置的 Key）
  try {
    const ds = encodeURIComponent(JSON.stringify({ keyWord: name }))
    const res = await fetch(`https://api.tianditu.gov.cn/geocoder?ds=${ds}&tk=${tiandituKey}`)
    if (res.ok) {
      const data = await res.json()
      const lon = data?.location?.lon
      const lat = data?.location?.lat
      if (typeof lon === 'number' && typeof lat === 'number') {
        const p: [number, number] = [lat, lon]
        cache.set(name, p)
        return p
      }
    }
  } catch {
    /* fallthrough */
  }

  // 2. Nominatim 兜底
  try {
    const res = await fetch(
      `https://nominatim.openstreetmap.org/search?q=${encodeURIComponent(name)}&format=json&limit=1`,
    )
    if (res.ok) {
      const data = await res.json()
      if (data[0]) {
        const p: [number, number] = [parseFloat(data[0].lat), parseFloat(data[0].lon)]
        cache.set(name, p)
        return p
      }
    }
  } catch {
    /* ignore */
  }

  cache.set(name, null)
  return null
}
