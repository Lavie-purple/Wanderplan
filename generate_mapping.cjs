const fs = require('fs');
const path = require('path');

function extractPoisFromCities(filePath) {
  const content = fs.readFileSync(filePath, 'utf8');
  const lines = content.split('\n');
  const pois = []; // each element: { id, name, cityName }
  let insidePois = false;
  let currentCityName = null;
  let poiLines = [];
  let collecting = false;
  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith('pois: [')) {
      insidePois = true;
      continue;
    }
    if (insidePois && trimmed.startsWith(']')) {
      insidePois = false;
      // flush any pending poi
      if (poiLines.length > 0) {
        const poi = parsePoiLines(poiLines);
        if (poi && currentCityName) {
          pois.push({ ...poi, cityName: currentCityName });
        }
        poiLines = [];
      }
      continue;
    }
    if (insidePois) {
      // check if line starts a poi object
      if (trimmed.startsWith('{')) {
        collecting = true;
        poiLines = [line];
        continue;
      }
      if (collecting) {
        poiLines.push(line);
        if (trimmed.endsWith('},') || trimmed.endsWith('}')) {
          // end of poi object
          const poi = parsePoiLines(poiLines);
          if (poi && currentCityName) {
            pois.push({ ...poi, cityName: currentCityName });
          }
          collecting = false;
          poiLines = [];
        }
        continue;
      }
      // look for city name
      const cityNameMatch = trimmed.match(/name:\s*'([^']+)'/);
      if (cityNameMatch) {
        currentCityName = cityNameMatch[1];
      }
    }
  }
  return pois;
}

function extractPoisFromExtra(filePath) {
  const content = fs.readFileSync(filePath, 'utf8');
  const lines = content.split('\n');
  const pois = [];
  let poiLines = [];
  let collecting = false;
  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith('{')) {
      collecting = true;
      poiLines = [line];
      continue;
    }
    if (collecting) {
      poiLines.push(line);
      if (trimmed.endsWith('},') || trimmed.endsWith('}')) {
        const poi = parsePoiLines(poiLines);
        if (poi) {
          pois.push(poi);
        }
        collecting = false;
        poiLines = [];
      }
    }
  }
  return pois;
}

function parsePoiLines(lines) {
  const text = lines.join('\n');
  const idMatch = text.match(/id:\s*'([^']+)'/);
  const nameMatch = text.match(/name:\s*'([^']+)'/);
  if (idMatch && nameMatch) {
    return { id: idMatch[1], name: nameMatch[1] };
  }
  return null;
}

